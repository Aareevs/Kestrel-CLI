package app

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/kestrel-cli/kestrel/internal/config"
	"github.com/kestrel-cli/kestrel/pkg/api"
)

// ErrConfigExists is returned by WriteConfig when a config file is already present.
var ErrConfigExists = errors.New("config file already exists")

// Proposal is a kestrel.yaml generated from discovery, not yet written.
type Proposal struct {
	Path     string // where it would be written
	YAML     []byte
	Enabled  []string // service names included
	Disabled []string // low-confidence services left commented out
	Inspect  *api.InspectResult
}

// ProposeConfig builds a kestrel.yaml from discovery. The result always
// passes config validation. Nothing is written.
func (a *App) ProposeConfig(ctx context.Context, o InspectOptions) (*Proposal, error) {
	res, err := a.Inspect(ctx, o)
	if err != nil {
		return nil, err
	}
	p := &Proposal{Path: filepath.Join(a.ProjectRoot, config.FileNames[0]), Inspect: res}
	name := filepath.Base(a.ProjectRoot)
	p.YAML, p.Enabled, p.Disabled = renderProposal(res, name, true)
	if _, err := config.Parse(p.Path, p.YAML, a.ProjectRoot); err != nil {
		// Inferred edges can form a cycle; fall back to declared ones only.
		p.YAML, p.Enabled, p.Disabled = renderProposal(res, name, false)
		if _, err := config.Parse(p.Path, p.YAML, a.ProjectRoot); err != nil {
			return nil, fmt.Errorf("generated config failed validation (this is a Kestrel bug): %w", err)
		}
	}
	return p, nil
}

// WriteConfig writes the proposal. It never overwrites an existing file.
func (a *App) WriteConfig(p *Proposal) error {
	if existing, err := a.ConfigPath(); err != nil {
		return err
	} else if existing != "" {
		return fmt.Errorf("%s: %w", existing, ErrConfigExists)
	}
	f, err := os.OpenFile(p.Path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		if errors.Is(err, os.ErrExist) {
			return fmt.Errorf("%s: %w", p.Path, ErrConfigExists)
		}
		return err
	}
	if _, err := f.Write(p.YAML); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

func q(s string) string {
	b, err := yaml.Marshal(s)
	if err != nil {
		return strconv.Quote(s)
	}
	return strings.TrimSuffix(string(b), "\n")
}

func renderProposal(res *api.InspectResult, rootName string, withInferred bool) (data []byte, enabled, disabled []string) {
	var b bytes.Buffer
	b.WriteString("# kestrel.yaml, generated by `kestrel init` from project discovery.\n")
	b.WriteString("# Each service notes where it was detected. Review the guesses before relying on them.\n")
	b.WriteString("# Reference: docs/configuration.md\n")
	fmt.Fprintf(&b, "version: %d\n", config.CurrentVersion)
	if name := strings.TrimSpace(rootName); name != "" {
		fmt.Fprintf(&b, "project:\n  name: %s\n", q(name))
	}

	var on, off []api.ServiceCandidate
	for _, c := range res.Candidates {
		if c.Command == nil && c.Health == nil {
			continue
		}
		if c.Confidence == api.ConfidenceLow {
			off = append(off, c)
		} else {
			on = append(on, c)
		}
	}
	included := map[string]bool{}
	for _, c := range on {
		included[c.Name] = true
	}

	switch {
	case len(on) == 0 && len(off) == 0:
		b.WriteString("services: []\n")
	default:
		b.WriteString("services:\n")
	}
	for _, c := range on {
		writeService(&b, c, included, withInferred, "")
		enabled = append(enabled, c.Name)
	}
	if len(off) > 0 {
		b.WriteString("\n  # Low-confidence candidates, left disabled. Uncomment to use.\n")
		for _, c := range off {
			writeService(&b, c, included, withInferred, "# ")
			disabled = append(disabled, c.Name)
		}
	}
	return b.Bytes(), enabled, disabled
}

func writeService(b *bytes.Buffer, c api.ServiceCandidate, included map[string]bool, withInferred bool, prefix string) {
	line := func(indent, s string) { fmt.Fprintf(b, "  %s%s%s\n", prefix, indent, s) }

	desc := c.Technology
	if c.Framework != "" {
		desc += " (" + c.Framework + ")"
	}
	if len(c.Sources) > 0 {
		src := c.Sources[0].File
		if c.Sources[0].Line > 0 {
			src += ":" + strconv.Itoa(c.Sources[0].Line)
		}
		desc += " · " + src
	}
	fmt.Fprintf(b, "  # %s · confidence %s\n", desc, c.Confidence)
	line("", "- name: "+q(c.Name))
	if c.Dir != "." && c.Dir != "" {
		line("  ", "dir: "+q(c.Dir))
	}
	if c.Command != nil {
		line("  ", "command: "+q(c.Command.Value))
	}

	var deps, notes []string
	for _, d := range c.DependsOn {
		switch {
		case d.Resolved && included[d.Name] && (d.Kind == api.DependencyDeclared || withInferred):
			deps = append(deps, q(d.Name))
		default:
			ref := d.Source.File
			if d.Source.Line > 0 {
				ref += ":" + strconv.Itoa(d.Source.Line)
			}
			why := "not detected as an enabled service"
			if d.Resolved && included[d.Name] {
				why = "omitted to avoid a dependency cycle"
			}
			notes = append(notes, fmt.Sprintf("may also need %s (%s, %s; %s)", d.Name, d.Kind, ref, why))
		}
	}
	if len(deps) > 0 {
		line("  ", "depends_on: ["+strings.Join(deps, ", ")+"]")
	}
	if h := c.Health; h != nil {
		line("  ", "health:")
		line("    ", "type: "+h.Type)
		switch h.Type {
		case config.HealthHTTP:
			line("    ", "url: "+q(h.Target))
		case config.HealthTCP:
			line("    ", "address: "+q(h.Target))
		}
	}
	for _, n := range notes {
		line("  ", "# "+n)
	}
}
