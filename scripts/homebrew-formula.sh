#!/bin/sh
# Renders the Homebrew formula for a Kestrel release from its checksums.txt.
#
#   scripts/homebrew-formula.sh v0.1.0 dist/checksums.txt > Formula/kestrel.rb
#
# The release workflow runs this and pushes the result to
# github.com/Aareevs/homebrew-tap. Archive names follow .goreleaser.yaml:
# kestrel_<version>_<os>_<arch>.tar.gz.
set -eu

[ $# -eq 2 ] || { echo "usage: $0 <tag> <checksums.txt>" >&2; exit 2; }
tag=$1
sums=$2
case "$tag" in v*) ;; *) tag="v$tag" ;; esac
version=${tag#v}
base="https://github.com/Aareevs/Kestrel-CLI/releases/download/$tag"

sha() { # sha <os> <arch>
	f="kestrel_${version}_$1_$2.tar.gz"
	s=$(awk -v f="$f" '$2 == f { print $1 }' "$sums")
	[ -n "$s" ] || { echo "$f is not in $sums" >&2; exit 1; }
	printf '%s' "$s"
}

# Looked up before rendering: a failure inside the heredoc's $(...) would only
# end that subshell and leave an empty checksum in the formula.
darwin_arm64=$(sha darwin arm64)
darwin_amd64=$(sha darwin amd64)
linux_arm64=$(sha linux arm64)
linux_amd64=$(sha linux amd64)

cat <<RUBY
# Generated by scripts/homebrew-formula.sh for Kestrel $tag. Do not edit by hand.
class Kestrel < Formula
  desc "Local-first debugging CLI that reconstructs what broke in your dev stack"
  homepage "https://github.com/Aareevs/Kestrel-CLI"
  version "$version"
  license "MIT"

  on_macos do
    if Hardware::CPU.arm?
      url "$base/kestrel_${version}_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    else
      url "$base/kestrel_${version}_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "$base/kestrel_${version}_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    else
      url "$base/kestrel_${version}_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "kestrel"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/kestrel version")
  end
end
RUBY
